"""data/*.json → web/js/medterm-data.js, web/js/medterm-ext-data.js, medterm-new-data.js, medterm-products-data.js (file:// 에서도 열리는 JS 변수 번들).
 - medterm-data.js     : window.MEDTERM_DATA(핵심 사전) · window.MEDTERM_CLASSES(분류 사전)
 - medterm-ext-data.js : window.MEDTERM_EXT(확장 수록: data/medterm_ext.json, 있을 때만 만든다)
 - medterm-new-data.js : window.MEDTERM_NEW(최신 승인·임상·화합물 연결: data/medterm_new.json, 있을 때만 만든다)
 - medterm-products-data.js : window.MEDTERM_PRODUCTS(국내 제품 계층: data/medterm_kr_products.json, 있을 때만 만든다)
 - medterm-law-data.js : window.MEDTERM_LAW(약사법 용어·기구 층: data/medterm_law.json ← build/law_build.py, 있을 때만 만든다)"""
import json, os
here = os.path.dirname(os.path.abspath(__file__)); root = os.path.dirname(here)
d = json.load(open(os.path.join(root, "data", "medterm.json"), encoding="utf-8")); c = json.load(open(os.path.join(root, "data", "class_lexicon.json"), encoding="utf-8"))
open(os.path.join(root, "web", "js", "medterm-data.js"), "w", encoding="utf-8").write(
  "/* generated by build/make_bundle.py \u2014 do not edit */\nwindow.MEDTERM_DATA=" + json.dumps(d, ensure_ascii=False, separators=(",", ":")) + ";\nwindow.MEDTERM_CLASSES=" + json.dumps(c, ensure_ascii=False, separators=(",", ":")) + ";\n")
print("bundle written", d["meta"]["counts"])
ext_path = os.path.join(root, "data", "medterm_ext.json")
if os.path.exists(ext_path):
    x = json.load(open(ext_path, encoding="utf-8"))
    open(os.path.join(root, "web", "js", "medterm-ext-data.js"), "w", encoding="utf-8", newline="\n").write(
      "/* generated by build/make_bundle.py \u2014 do not edit (확장 수록: 자동 수집 초안, 약사 검수 전) */\nwindow.MEDTERM_EXT=" + json.dumps(x, ensure_ascii=False, separators=(",", ":")) + ";\n")
    print("ext bundle written", x["meta"]["counts"]["entities"], "entities")
for fname, var, out, label in (("medterm_new.json", "MEDTERM_NEW", "medterm-new-data.js", "최신 승인·임상·화합물 연결, 약사 검수 전"),
                               ("medterm_kr_products.json", "MEDTERM_PRODUCTS", "medterm-products-data.js", "국내 제품 계층, 약사 검수 전"),
                               ("medterm_law.json", "MEDTERM_LAW", "medterm-law-data.js", "약사법 용어·기구 층, 약사 검수 전")):
    src = os.path.join(root, "data", fname)
    if os.path.exists(src):
        o = json.load(open(src, encoding="utf-8"))
        open(os.path.join(root, "web", "js", out), "w", encoding="utf-8", newline="\n").write(
          "/* generated by build/make_bundle.py \u2014 do not edit (" + label + ") */\nwindow." + var + "=" + json.dumps(o, ensure_ascii=False, separators=(",", ":")) + ";\n")
        print(out, "written", len(json.dumps(o, ensure_ascii=False, separators=(",", ":"))), "chars")
